#!/usr/bin/env python3
"""Extract, merge and compile the os-ipv6-ha gettext catalogs.

Stdlib only, so this runs on macOS, Linux and the FreeBSD CI image without
gettext-tools installed.  Every output is deterministic (no timestamps, stable
ordering), which is what lets `check` diff a freshly generated template against
the committed one.
"""
import argparse
from dataclasses import dataclass, field
from pathlib import Path
import re
import struct
import sys
import xml.parsers.expat


ROOT = Path(__file__).resolve().parents[1]
DOMAIN = 'os-ipv6-ha'
LOCALE_DIR = 'locale'
MO_DIR = 'src/share/locale'
POT_NAME = f'{DOMAIN}.pot'

POT_COMMENTS = (
    f'# Translation template for the {DOMAIN} OPNsense plugin.',
    '# Generated by tools/i18n.py extract -- do not edit by hand.',
    '# This file is distributed under the same license as the plugin.',
    '#',
)
_HEADER_FIELDS = (
    f'Project-Id-Version: {DOMAIN}\n',
    'Report-Msgid-Bugs-To: \n',
    'MIME-Version: 1.0\n',
    'Content-Type: text/plain; charset=UTF-8\n',
    'Content-Transfer-Encoding: 8bit\n',
)
POT_HEADER = ''.join(_HEADER_FIELDS) + 'Language: \n'

# PHP: gettext('x'), I18n::gettext('x'), \OPNsense\IPv6HA\I18n::gettext('x'), dgettext('os-ipv6-ha', 'x').
# The lookbehind keeps ->gettext( and $gettext( out; \b already excludes ngettext/dngettext.
PHP_CALL = re.compile(r'(?<![\w$>])(?:(?:\\?[A-Za-z_][\w\\]*)::\s*)?(?P<fn>d?gettext)\s*\(')
VOLT_CALL = re.compile(r'(?<![\w$>.])lang\._\s*\(')

# PHP double-quoted escapes we resolve; anything else keeps its backslash (PHP semantics).
_DQ_ESCAPES = {'n': '\n', 't': '\t', 'r': '\r', 'v': '\v', 'f': '\f', 'e': '\x1b',
               '\\': '\\', '$': '$', '"': '"'}
_INTERPOLATION = re.compile(r'\$[A-Za-z_{]')

_ESCAPE_MAP = str.maketrans({'\\': '\\\\', '"': '\\"', '\n': '\\n', '\t': '\\t', '\r': '\\r'})
_UNESCAPE = {'n': '\n', 't': '\t', 'r': '\r', '"': '"', '\\': '\\', "'": "'", 'a': '\a', 'b': '\b',
             'f': '\f', 'v': '\v'}


@dataclass
class Entry:
    """One catalog entry.  Plurals and contexts are deliberately unsupported."""

    msgid: str
    msgstr: str = ''
    refs: list = field(default_factory=list)
    flags: list = field(default_factory=list)
    comments: list = field(default_factory=list)
    auto_comments: list = field(default_factory=list)


class CatalogError(ValueError):
    """Raised for malformed sources or catalogs."""


# --------------------------------------------------------------------------- sources

def _line_of(text, offset):
    return text.count('\n', 0, offset) + 1


def _read_literal(text, index, allow_interpolation=True):
    """Parse the PHP/Volt string literal at text[index:]; return (value, end_index)."""
    if index >= len(text) or text[index] not in ('"', "'"):
        return None, index
    quote = text[index]
    out = []
    i = index + 1
    while i < len(text):
        char = text[i]
        if char == '\\':
            following = text[i + 1] if i + 1 < len(text) else ''
            if quote == "'":
                # PHP single quotes only escape the quote and the backslash itself.
                if following in ("'", '\\'):
                    out.append(following)
                    i += 2
                    continue
                out.append(char)
                i += 1
                continue
            if following in _DQ_ESCAPES:
                out.append(_DQ_ESCAPES[following])
                i += 2
                continue
            if following == 'x' and re.match(r'[0-9A-Fa-f]{1,2}', text[i + 2:i + 4]):
                digits = re.match(r'[0-9A-Fa-f]{1,2}', text[i + 2:i + 4]).group(0)
                out.append(chr(int(digits, 16)))
                i += 2 + len(digits)
                continue
            out.append(char)
            i += 1
            continue
        if char == quote:
            value = ''.join(out)
            if quote == '"' and not allow_interpolation and _INTERPOLATION.search(value):
                return None, i + 1
            return value, i + 1
        out.append(char)
        i += 1
    return None, index


def _skip_space(text, index):
    while index < len(text) and text[index] in ' \t\r\n':
        index += 1
    return index


def scan_php(text):
    """Yield (msgid, line) for gettext-family calls with a literal argument."""
    for match in PHP_CALL.finditer(text):
        index = _skip_space(text, match.end())
        value, index = _read_literal(text, index, allow_interpolation=False)
        if value is None:
            continue
        if match.group('fn') == 'dgettext':
            if value != DOMAIN:
                continue
            index = _skip_space(text, index)
            if index >= len(text) or text[index] != ',':
                continue
            index = _skip_space(text, index + 1)
            value, index = _read_literal(text, index, allow_interpolation=False)
            if value is None:
                continue
        if value:
            yield value, _line_of(text, match.start())


def scan_volt(text):
    """Yield (msgid, line) for lang._('...') calls."""
    for match in VOLT_CALL.finditer(text):
        index = _skip_space(text, match.end())
        value, index = _read_literal(text, index)
        if value:
            yield value, _line_of(text, match.start())


class _Node:
    """Minimal XML node that remembers the line its start tag was on."""

    __slots__ = ('tag', 'attrib', 'text', 'line', 'children')

    def __init__(self, tag, attrib, line):
        self.tag = tag
        self.attrib = attrib
        self.text = ''
        self.line = line
        self.children = []


def parse_xml(path):
    """Parse an XML file into _Node objects (expat gives us the line numbers)."""
    root = _Node('', {}, 1)
    stack = [root]
    parser = xml.parsers.expat.ParserCreate()

    def start(name, attrs):
        node = _Node(name, attrs, parser.CurrentLineNumber)
        stack[-1].children.append(node)
        stack.append(node)

    def end(_name):
        stack.pop()

    def chars(data):
        stack[-1].text += data

    parser.StartElementHandler = start
    parser.EndElementHandler = end
    parser.CharacterDataHandler = chars
    with open(path, 'rb') as handle:
        parser.ParseFile(handle)
    if not root.children:
        raise CatalogError(f'{path}: empty document')
    return root.children[0]


def _walk(node):
    yield node
    for child in node.children:
        yield from _walk(child)


def scan_form(root):
    """Form XML: <label>, <help>, <hint> text plus tab/subtab description attributes."""
    for node in _walk(root):
        if node.tag in ('label', 'help', 'hint'):
            yield node.text, node.line
        if 'description' in node.attrib:
            yield node.attrib['description'], node.line


def scan_model(root):
    """Model XML: <ValidationMessage>, <BlankDesc> and the <OptionValues> children."""
    for node in _walk(root):
        if node.tag in ('ValidationMessage', 'BlankDesc'):
            yield node.text, node.line
        elif node.tag == 'OptionValues':
            for child in node.children:
                if child.children:
                    # Option group: the group caption plus every option below it.
                    yield child.attrib.get('value', child.tag), child.line
                    for option in child.children:
                        yield option.text, option.line
                else:
                    yield child.text, child.line


def scan_menu(root):
    """Menu XML: VisibleName attributes (entries carrying `visibility` are skipped)."""
    for node in _walk(root):
        if 'visibility' not in node.attrib and 'VisibleName' in node.attrib:
            yield node.attrib['VisibleName'], node.line


def scan_acl(root):
    """ACL XML: <name> and <description> text."""
    for node in _walk(root):
        if node.tag in ('name', 'description'):
            yield node.text, node.line


_XML_SCANNERS = {'form': scan_form, 'model': scan_model, 'menu': scan_menu, 'acl': scan_acl}


def collect_messages(root=ROOT):
    """Return {msgid: [(relative path, line), ...]} for the whole source tree."""
    messages = {}

    def add(value, path, line):
        if not value:
            return
        reference = (path.relative_to(root).as_posix(), line)
        references = messages.setdefault(value, [])
        if reference not in references:
            references.append(reference)

    source = root / 'src'
    if not source.is_dir():
        return messages
    for path in sorted(source.rglob('*.php')):
        text = path.read_text(encoding='utf-8')
        for value, line in scan_php(text):
            add(value, path, line)
    for path in sorted(source.rglob('*.volt')):
        text = path.read_text(encoding='utf-8')
        for value, line in scan_volt(text):
            add(value, path, line)
    for path in sorted(source.rglob('*.xml')):
        node = parse_xml(path)
        scanner = _XML_SCANNERS.get(node.tag)
        if scanner is None:
            continue
        for value, line in scanner(node):
            # XML text carries the surrounding indentation; the runtime strings do not.
            add((value or '').strip(), path, line)
    return messages


def build_entries(messages):
    """Turn collected messages into entries ordered by their first reference."""
    entries = []
    for msgid, references in messages.items():
        entries.append(Entry(msgid=msgid, refs=sorted(set(references))))
    entries.sort(key=lambda entry: (entry.refs[0][0], entry.refs[0][1], entry.msgid))
    return entries


# --------------------------------------------------------------------------- catalogs

def escape(value):
    return value.translate(_ESCAPE_MAP)


def unescape(value):
    out = []
    index = 0
    while index < len(value):
        char = value[index]
        if char == '\\' and index + 1 < len(value):
            following = value[index + 1]
            out.append(_UNESCAPE.get(following, following))
            index += 2
            continue
        out.append(char)
        index += 1
    return ''.join(out)


def _string_lines(prefix, value):
    if '\n' not in value:
        return [f'{prefix} "{escape(value)}"']
    chunks = value.split('\n')
    parts = [chunk + '\n' for chunk in chunks[:-1]]
    if chunks[-1]:
        parts.append(chunks[-1])
    return [f'{prefix} ""'] + [f'"{escape(part)}"' for part in parts]


def _reference_lines(references, width=78):
    lines = []
    current = '#:'
    for path, line in references:
        token = f' {path}:{line}'
        if len(current) + len(token) > width and current != '#:':
            lines.append(current)
            current = '#:'
        current += token
    if current != '#:':
        lines.append(current)
    return lines


def render_catalog(entries, header, comments=()):
    """Render a .pot/.po file body; identical inputs always give identical bytes."""
    lines = list(comments)
    lines.append('msgid ""')
    lines.extend(_string_lines('msgstr', header))
    for entry in entries:
        lines.append('')
        lines.extend(f'#{" " + text if text else ""}' for text in entry.comments)
        lines.extend(f'#. {text}' for text in entry.auto_comments)
        lines.extend(_reference_lines(entry.refs))
        if entry.flags:
            lines.append('#, ' + ', '.join(entry.flags))
        lines.extend(_string_lines('msgid', entry.msgid))
        lines.extend(_string_lines('msgstr', entry.msgstr))
    return '\n'.join(lines) + '\n'


def parse_catalog(text, name='<catalog>'):
    """Parse a .po/.pot file into (header msgstr, entries).  Obsolete blocks are dropped."""
    entries = []
    header = ''
    state = {'comments': [], 'auto': [], 'refs': [], 'flags': [], 'msgid': None, 'msgstr': None}
    field_name = None

    def reset():
        return {'comments': [], 'auto': [], 'refs': [], 'flags': [], 'msgid': None, 'msgstr': None}

    def flush():
        nonlocal state, field_name, header
        if state['msgid'] is not None:
            if state['msgid'] == '':
                header = state['msgstr'] or ''
            else:
                entries.append(Entry(msgid=state['msgid'], msgstr=state['msgstr'] or '',
                                     refs=state['refs'], flags=state['flags'],
                                     comments=state['comments'], auto_comments=state['auto']))
        state = reset()
        field_name = None

    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line:
            flush()
            continue
        if line.startswith('#'):
            if state['msgid'] is not None:
                flush()
            if line.startswith('#~') or line.startswith('#|'):
                continue  # obsolete / previous-msgid blocks are not carried over
            if line.startswith('#:'):
                for token in line[2:].split():
                    path, _, position = token.rpartition(':')
                    state['refs'].append((path, int(position)) if position.isdigit() else (token, 0))
            elif line.startswith('#,'):
                state['flags'].extend(flag.strip() for flag in line[2:].split(',') if flag.strip())
            elif line.startswith('#.'):
                state['auto'].append(line[2:].strip())
            else:
                state['comments'].append(line[1:].strip())
            continue
        keyword, _, rest = line.partition(' ')
        if keyword in ('msgctxt', 'msgid_plural') or keyword.startswith('msgstr['):
            raise CatalogError(f'{name}:{number}: plural forms and message contexts are not supported')
        if keyword in ('msgid', 'msgstr'):
            if keyword == 'msgid' and state['msgid'] is not None:
                flush()
            field_name = keyword
            state[field_name] = unescape(rest.strip()[1:-1])
            continue
        if line.startswith('"') and field_name:
            state[field_name] += unescape(line[1:-1])
            continue
        raise CatalogError(f'{name}:{number}: cannot parse {raw!r}')
    flush()
    return header, entries


def read_catalog(path):
    return parse_catalog(path.read_text(encoding='utf-8'), path.name)


def normalize_header(header, language=''):
    """Force a UTF-8 Content-Type (and a Language field) into a catalog header."""
    lines = [line + '\n' for line in header.split('\n') if line]
    kept = []
    for line in lines:
        lowered = line.lower()
        if lowered.startswith(('content-type:', 'content-transfer-encoding:')):
            continue
        if language and lowered.startswith('language:') and not line.partition(':')[2].strip():
            line = f'Language: {language}\n'  # a fresh catalog inherits the empty template field
        kept.append(line)
    if language and not any(line.lower().startswith('language:') for line in kept):
        kept.append(f'Language: {language}\n')
    kept.append('Content-Type: text/plain; charset=UTF-8\n')
    kept.append('Content-Transfer-Encoding: 8bit\n')
    return ''.join(kept)


def mo_bytes(catalog):
    """Serialize {msgid: msgstr} as a little-endian GNU .mo file without a hash table."""
    items = sorted(((key.encode('utf-8'), value.encode('utf-8')) for key, value in catalog.items()),
                   key=lambda pair: pair[0])
    keys = bytearray()
    values = bytearray()
    offsets = []
    for key, value in items:
        offsets.append((len(keys), len(key), len(values), len(value)))
        keys += key + b'\x00'
        values += value + b'\x00'
    key_start = 7 * 4 + 16 * len(items)
    value_start = key_start + len(keys)
    table = bytearray()
    for key_offset, key_length, _, _ in offsets:
        table += struct.pack('<II', key_length, key_offset + key_start)
    for _, _, value_offset, value_length in offsets:
        table += struct.pack('<II', value_length, value_offset + value_start)
    # magic, revision, count, originals table, translations table, hash size, hash offset
    head = struct.pack('<7I', 0x950412de, 0, len(items), 7 * 4, 7 * 4 + len(items) * 8, 0, key_start)
    return head + bytes(table) + bytes(keys) + bytes(values)


# --------------------------------------------------------------------------- commands

def locale_dir(root):
    return root / LOCALE_DIR


def pot_path(root):
    return locale_dir(root) / POT_NAME


def po_files(root, locales=None):
    paths = sorted(locale_dir(root).glob('*.po')) if locale_dir(root).is_dir() else []
    if locales:
        wanted = set(locales)
        paths = [path for path in paths if path.stem in wanted]
    return paths


def mo_path(root, language):
    return root / MO_DIR / language / 'LC_MESSAGES' / f'{DOMAIN}.mo'


def render_template(root=ROOT):
    return render_catalog(build_entries(collect_messages(root)), POT_HEADER, POT_COMMENTS)


def write_if_changed(path, data):
    """Write only on change so repeated runs leave mtimes (and git) alone."""
    binary = isinstance(data, bytes)
    if path.exists():
        current = path.read_bytes() if binary else path.read_text(encoding='utf-8')
        if current == data:
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    if binary:
        path.write_bytes(data)
    else:
        path.write_text(data, encoding='utf-8')
    return True


def command_extract(args):
    root = args.root
    entries = build_entries(collect_messages(root))
    content = render_catalog(entries, POT_HEADER, POT_COMMENTS)
    if args.stdout:
        sys.stdout.write(content)
        return 0
    target = Path(args.output) if args.output else pot_path(root)
    changed = write_if_changed(target, content)
    print(f'{"wrote" if changed else "unchanged"} {target} ({len(entries)} messages)')
    return 0


def merge(template_entries, header, entries, language):
    """Merge the template into one catalog: keep msgstr, add new ids, drop removed ids."""
    existing = {entry.msgid: entry for entry in entries}
    merged = []
    for entry in template_entries:
        old = existing.get(entry.msgid)
        merged.append(Entry(msgid=entry.msgid,
                            msgstr=old.msgstr if old else '',
                            refs=entry.refs,
                            flags=list(old.flags) if old else [],
                            comments=list(old.comments) if old else [],
                            auto_comments=list(old.auto_comments) if old else []))
    added = sum(1 for entry in template_entries if entry.msgid not in existing)
    removed = sum(1 for msgid in existing if msgid not in {e.msgid for e in template_entries})
    return render_catalog(merged, normalize_header(header, language), ()), added, removed


def command_update(args):
    root = args.root
    template = pot_path(root)
    if not template.exists():
        print(f'{template} is missing; run "i18n.py extract" first', file=sys.stderr)
        return 1
    _, template_entries = read_catalog(template)
    targets = po_files(root, args.locale)
    if args.locale:
        for language in args.locale:
            path = locale_dir(root) / f'{language}.po'
            if path not in targets:
                targets.append(path)
        targets.sort()
    if not targets:
        print(f'no catalogs in {locale_dir(root)}; pass --locale to create one')
        return 0
    for path in targets:
        header, entries = read_catalog(path) if path.exists() else (POT_HEADER, [])
        content, added, removed = merge(template_entries, header, entries, path.stem)
        changed = write_if_changed(path, content)
        print(f'{"wrote" if changed else "unchanged"} {path} '
              f'({len(template_entries)} messages, +{added} -{removed})')
    return 0


def catalog_for(path):
    """Translations of one .po, ready for the .mo writer (fuzzy/untranslated dropped)."""
    header, entries = read_catalog(path)
    catalog = {'': normalize_header(header, path.stem)}
    for entry in entries:
        if entry.msgstr and 'fuzzy' not in entry.flags:
            catalog[entry.msgid] = entry.msgstr
    return catalog


def command_compile(args):
    root = args.root
    paths = po_files(root, args.locale)
    if not paths:
        print(f'no catalogs in {locale_dir(root)}; nothing to compile')
        return 0
    for path in paths:
        catalog = catalog_for(path)
        target = Path(args.output) / path.stem / 'LC_MESSAGES' / f'{DOMAIN}.mo' if args.output \
            else mo_path(root, path.stem)
        changed = write_if_changed(target, mo_bytes(catalog))
        print(f'{"wrote" if changed else "unchanged"} {target} ({len(catalog) - 1} translations)')
    return 0


def check(root=ROOT):
    """Return a list of problems.  An empty locale/ directory is not a problem."""
    problems = []
    template = pot_path(root)
    catalogs = po_files(root)
    if not template.exists():
        if catalogs:
            problems.append(f'{template} is missing while {len(catalogs)} catalog(s) exist; '
                            f'run "tools/i18n.py extract"')
        return problems  # nothing translated yet: the migration has not landed
    expected = render_template(root)
    if template.read_text(encoding='utf-8') != expected:
        problems.append(f'{template} is out of date; run "tools/i18n.py extract"')
    _, template_entries = parse_catalog(expected, template.name)
    template_ids = [entry.msgid for entry in template_entries]
    for path in catalogs:
        _, entries = read_catalog(path)
        known = {entry.msgid for entry in entries}
        missing = [msgid for msgid in template_ids if msgid not in known]
        if missing:
            problems.append(f'{path} is missing {len(missing)} message(s), first: {missing[0]!r}; '
                            f'run "tools/i18n.py update"')
        target = mo_path(root, path.stem)
        expected_mo = mo_bytes(catalog_for(path))
        if not target.exists():
            problems.append(f'{target} is missing; run "tools/i18n.py compile"')
        elif target.read_bytes() != expected_mo:
            problems.append(f'{target} is out of date; run "tools/i18n.py compile"')
    return problems


def command_check(args):
    problems = check(args.root)
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    if not pot_path(args.root).exists():
        print('i18n check passed (no catalogs yet)')
    else:
        print(f'i18n check passed ({len(po_files(args.root))} catalog(s))')
    return 0


def parser():
    root = argparse.ArgumentParser(
        prog='i18n.py',
        description=f'Manage the {DOMAIN} gettext catalogs (extract -> update -> translate -> '
                    f'compile -> check).',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='Sources scanned by extract:\n'
               "  PHP    gettext('x'), I18n::gettext('x'), dgettext('%s', 'x')\n"
               "  Volt   lang._('x')\n"
               '  XML    form label/help/hint and description attributes, model\n'
               '         ValidationMessage/BlankDesc/OptionValues, menu VisibleName,\n'
               '         ACL name/description\n' % DOMAIN)
    root.add_argument('--root', type=Path, default=ROOT, metavar='DIR',
                      help='repository root to operate on (default: %(default)s)')
    commands = root.add_subparsers(dest='command', required=True)

    extract = commands.add_parser('extract', help=f'regenerate {LOCALE_DIR}/{POT_NAME}')
    extract.add_argument('-o', '--output', metavar='PATH', help='write the template elsewhere')
    extract.add_argument('--stdout', action='store_true', help='print the template instead')
    extract.set_defaults(handler=command_extract)

    update = commands.add_parser(
        'update', help=f'merge the template into {LOCALE_DIR}/*.po',
        description='Merge the template into every catalog: existing msgstr values are kept, new '
                    'messages are added with an empty msgstr, and messages that left the template '
                    'are dropped (they are NOT kept as #~ obsolete entries).')
    update.add_argument('--locale', action='append', metavar='LANG',
                        help='only this locale, creating the file when absent (repeatable)')
    update.set_defaults(handler=command_update)

    build = commands.add_parser('compile', help=f'write {MO_DIR}/<lang>/LC_MESSAGES/{DOMAIN}.mo',
                                description='Compile every catalog to a GNU .mo file. Fuzzy and '
                                            'untranslated entries are skipped.')
    build.add_argument('--locale', action='append', metavar='LANG', help='only this locale (repeatable)')
    build.add_argument('-o', '--output', metavar='DIR', help='write the .mo tree elsewhere')
    build.set_defaults(handler=command_compile)

    verify = commands.add_parser(
        'check', help='verify template, catalogs and .mo files are in sync',
        description='Exit 1 when the template is out of date, when a catalog lacks a message from '
                    'the template, or when a .mo differs from what compile would write. An empty '
                    f'{LOCALE_DIR}/ directory (migration not landed yet) passes.')
    verify.set_defaults(handler=command_check)
    return root


def main(argv=None):
    args = parser().parse_args(argv)
    return args.handler(args)


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (CatalogError, OSError, xml.parsers.expat.ExpatError) as error:
        print(error, file=sys.stderr)
        raise SystemExit(1)
